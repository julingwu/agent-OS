import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const storage = new Map();
globalThis.localStorage = { getItem: k => storage.get(k) ?? null, setItem: (k,v) => storage.set(k,v), removeItem: k => storage.delete(k) };
globalThis.location = { hostname: 'localhost', protocol: 'http:' };
globalThis.window = new EventTarget();
const requests = [];
globalThis.fetch = () => new Promise(resolve => requests.push(resolve));
const source = readFileSync(new URL('../src/api.js', import.meta.url), 'utf8');
const { api, auth } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const response = (body, status=200) => new Response(JSON.stringify(body), { status, headers: {'content-type':'application/json'} });
const stale = pending => assert.rejects(pending, error => error.stale === true);
for (const status of [200, 401]) {
  auth.set('synthetic-A');
  const pending = api.org();
  const rejected = stale(pending);
  auth.set('synthetic-B');
  requests.shift()(response(status === 200 ? { roots: ['private-A'] } : { detail: {code:'NotLoggedIn'} }, status));
  await rejected;
  assert.equal(auth.get(), 'synthetic-B');
}
for (const status of [200, 401]) {
  auth.clear();
  const pending = api.login('A', 'synthetic-only');
  const rejected = stale(pending);
  auth.set('synthetic-B');
  requests.shift()(response(status === 200 ? {token:'synthetic-A'} : {detail:{code:'BadCredentials'}}, status));
  await rejected;
  assert.equal(auth.get(), 'synthetic-B');
}
auth.set('synthetic-A');
const logout = api.logout();
auth.set('synthetic-B');
requests.shift()(response({detail:{code:'NotLoggedIn'}}, 401));
await logout;
assert.equal(auth.get(), 'synthetic-B');
auth.clear();
auth.bindScope({identity_id:'A',tenant_id:'HQ',entity_id:'HQ',role:'ceo'});
const cookieRequest = api.org();
const cookieStale = stale(cookieRequest);
auth.bindScope({identity_id:'B',tenant_id:'BETA',entity_id:'BETA',role:'ceo'});
requests.shift()(response({roots:['private-A']}));
await cookieStale;
auth.set('synthetic-A');
let parsed;
const delayedBody = api.org();
const delayedStale = stale(delayedBody);
requests.shift()({ok:true,json:() => new Promise(resolve => { parsed=resolve; })});
await new Promise(resolve => setImmediate(resolve));
auth.set('synthetic-B');
parsed({roots:['private-A']});
await delayedStale;
console.log('7 API session-race assertions passed (late success/401, login/logout, cookie scope, delayed JSON).');
auth.set('synthetic-A');
const closing = api.logout();
const relogin = api.login('B', 'synthetic-only');
assert.equal(requests.length, 1, 'Login must not race an outstanding logout Set-Cookie');
requests.shift()(response({ok:true}));
await closing;
await new Promise(resolve => setImmediate(resolve));
assert.equal(requests.length, 1);
requests.shift()(response({token:'synthetic-B'}));
await relogin;
assert.equal(auth.get(), 'synthetic-B');
console.log('Logout/login cookie writes are serialized. Total: 8 race scenarios passed.');
