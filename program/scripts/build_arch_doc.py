def mdclean(t: str) -> str:
    """Convert the inline HTML used in content into Markdown-safe text."""
    return (str(t).replace("<b>", "**").replace("</b>", "**")
            .replace("<u>", "").replace("</u>", "")
            .replace("<code>", "`").replace("</code>", "`")
            .replace("<br>", " ").replace("|", "/"))


def render_md() -> str:
    out = [f"# {TITLE}", "", f"> {VERSION} · 代码基线 mainline @ 924346b", ""]
    for s in S:
        out.append(f"\n## {s['title']}\n")
        for kind, payload in s["blocks"]:
            if kind == "p":
                out.append(mdclean(payload) + "\n")
            elif kind == "h3":
                out.append(f"### {mdclean(payload)}\n")
            elif kind == "ul":
                out.extend(f"- {mdclean(x)}" for x in payload)
                out.append("")
            elif kind == "ol":
                out.extend(f"{i}. {mdclean(x)}" for i, x in enumerate(payload, 1))
                out.append("")
            elif kind == "table":
                headers, rows = payload
                out.append("| " + " | ".join(mdclean(h) for h in headers) + " |")
                out.append("|" + "|".join(["---"] * len(headers)) + "|")
                for r in rows:
                    out.append("| " + " | ".join(mdclean(c) for c in r) + " |")
                out.append("")
            elif kind == "note":
                out.append("> " + mdclean(payload) + "\n")
            elif kind in ("layer", "steps"):
                for a, b in payload:
                    out.append(f"- **{mdclean(a)}**：" + (mdclean(b) if isinstance(b, str) else "；".join(mdclean(x) for x in b)))
                out.append("")
            elif kind == "code":
                out.append("```\n" + payload + "\n```\n")
    return "\n".join(out)


